import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {reportAudit,isRecoverableWeakProduct} from '../assets/release-11.17.0/report-audit.js';
const bare={barcode:'3017620422003',name:'Example',nutrition:{kcal:null,protein:null,carbohydrates:null,sugars:null,fat:null,saturatedFat:null,fiber:null,salt:null},basis:null};
assert.equal(reportAudit(bare).reason,'missing');
assert.equal(reportAudit(bare).known,0);
assert(isRecoverableWeakProduct(bare));
assert.equal(reportAudit({...bare,basis:'g',nutrition:{...bare.nutrition,kcal:500,protein:10}}).safeToCalculate,true);
assert.equal(reportAudit({...bare,nutrition:{...bare.nutrition,kcal:500,protein:10}}).reason,'unit');
assert.equal(reportAudit({...bare,basis:'g',nutrition:{...bare.nutrition,kcal:500,protein:10},partial:true}).safeToCalculate,false);
const html=await fs.readFile('index.html','utf8');
const inline=html.split('<script type="importmap">')[1]?.split('</script>')[0];assert(inline);
const hash='sha256-'+crypto.createHash('sha256').update(inline).digest('base64');
assert((await fs.readFile('_headers','utf8')).includes(hash),'Import map CSP mismatch');
for(const path of Object.values(JSON.parse(inline).imports))await fs.stat('.'+path);
for(const name of ['app.css','app.js','result.js','model.js','report-audit.js','api-core.js','api.js','engine.js'])await fs.stat('assets/release-11.17.0/'+name);
assert((await fs.readFile('sw.js','utf8')).includes('foodscan-shell-11.17.0'));
const worker=await fs.readFile('_worker.js','utf8');
assert(worker.includes("X-FoodScan-Quality"));
assert(worker.includes("sourceQuality(product).usable"));
console.log('PASS nutrition report integrity + CSP');
