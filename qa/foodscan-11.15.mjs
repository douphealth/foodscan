import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {improveRecord,frontPhotos} from '../assets/release-11.15.0/record-quality.js';
const p={barcode:'5740900401365',name:'Lurpak',basis:'g',servingAmount:null,servingUnit:null,
 nutrition:{kcal:14579.3499043977,sugars:.6,carbohydrates:.6,fat:75,saturatedFat:35,protein:.5,fiber:null,salt:.885,sodium:354},servingNutrition:{}};
const source={nutriments:{'energy-kcal_100g':14579.3499043977,'energy-kj_100g':2793.7,'fat_100g':75,'saturated-fat_100g':35,'carbohydrates_100g':.6,'sugars_100g':.6,'proteins_100g':.5,'salt_100g':.885}};
const checked=improveRecord(p,source);
assert(Math.abs(checked.nutrition.kcal-2793.7/4.184)<.0001);
assert.equal(checked.nutritionQuality.origins.kcal,'kilojoules');
assert(checked.nutritionQuality.issues.some(x=>x.includes('kcal')));
assert.equal(checked.nutrition.fiber,null);
assert(checked.nutritionQuality.missing.includes('Fiber'));
const wrong=improveRecord({...p,nutrition:{...p.nutrition,kcal:500}}, {...source,nutriments:{...source.nutriments,'energy-kcal_100g':500}});
assert.equal(wrong.nutrition.kcal,null,'two plausible but inconsistent energy fields must be withheld');
const derived=improveRecord({...p,servingAmount:25,servingUnit:'g',nutrition:{...p.nutrition,protein:null}}, {nutriments:{'proteins_serving':3,'energy-kcal_100g':420,'energy-kj_100g':1757}});
assert.equal(derived.nutrition.protein,12);
assert(derived.nutritionQuality.derived.includes('Protein'));
const missing=improveRecord({...p,nutrition:{...p.nutrition,sugars:null}},{nutriments:{'sugars_serving':2}});
assert.equal(missing.nutrition.sugars,null,'no inferred 100g number without confirmed serving');
const invalid=improveRecord({...p,nutrition:{...p.nutrition,sugars:90,carbohydrates:2}},{nutriments:{'sugars_100g':90,'carbohydrates_100g':2}});
assert.equal(invalid.nutrition.sugars,null);
assert.equal(invalid.nutrition.carbohydrates,null);
const image='https://images.openfoodfacts.org/images/products/301/762/042/2003/front_el.20.400.jpg';
const photos=frontPhotos({selected_images:{front:{display:{el:image,en:'https://images.openfoodfacts.org/images/products/301/762/042/2003/front_en.20.400.jpg'}}},image_url:'https://hostile.example/p.png'},'3017620422003',['el-GR']);
assert.equal(photos[0],image);
assert(!photos.some(x=>x.includes('hostile')));
const html=await fs.readFile('index.html','utf8');
const im=html.split('<script type="importmap">')[1]?.split('</script>')[0];
assert(im);
const h='sha256-'+crypto.createHash('sha256').update(im).digest('base64');
assert((await fs.readFile('_headers','utf8')).includes(h),'CSP hash mismatch');
for(const p of Object.values(JSON.parse(im).imports))await fs.stat('.'+p);
assert(html.includes('"softwareVersion":"11.19.0"'));
const worker=await fs.readFile('_worker.js','utf8');
assert(worker.includes('selected_images'));
assert(worker.includes('nutrition_data_per'));
const styles=await fs.readFile('assets/release-11.15.0/app.css','utf8');
assert(styles.includes('object-fit:contain'));
const cache=await fs.readFile('sw.js','utf8');
assert(cache.includes('foodscan-shell-11.19.0'));
console.log('FoodScan 11.15 source validation PASS');
