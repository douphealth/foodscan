import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {categoryProviderUrls,searchBrowserCategory} from '../assets/release-11.13.0/category-direct.js';

const urls=categoryProviderUrls('en:hazelnut-spreads',{country:'france',full:false});
assert.equal(urls.length,2);
assert.match(new URL(urls[0].url).searchParams.get('q'),/categories_tags:"en:hazelnut-spreads"/);
assert.match(new URL(urls[0].url).searchParams.get('q'),/countries_tags:"en:france"/);
assert.equal(urls[0].index,true);
assert.equal(categoryProviderUrls('en:hazelnut-spreads',{full:true})[0].index,false);
assert.throws(()=>categoryProviderUrls('https://attacker.invalid'));
let calls=0;
const hit={code:'3017620422003',product_name:'Hazelnut spread',brands:['Ferrero'],categories_tags:['en:hazelnut-spreads'],nova_group:'4',nutriments:{sugars_100g:57}};
const validBarcode=x=>x==='3017620422003';
const parseRecord=({product})=>product;
const successful=async(url,init)=>{calls++;return new Response(JSON.stringify({hits:[hit]}),{status:200,headers:{'content-type':'application/json'}});};
const result=await searchBrowserCategory('en:hazelnut-spreads',{parseRecord,validBarcode,fetcher:successful});
assert.equal(calls,1);
assert.equal(result.transport,'browser');
assert.equal(result.products.length,1);
assert.equal(result.products[0].partial,true);
assert.equal(result.products[0].brands,'Ferrero');
assert.equal(result.products[0].nova_group,4);
const broken=async(url)=>new Response('bad gateway',{status:502,headers:{'content-type':'text/html'}});
const recovered=await searchBrowserCategory('en:hazelnut-spreads',{full:true,parseRecord,validBarcode,fetcher:async(url)=>{if(url.startsWith('https://world.'))return broken(url);return successful(url);}});
assert.equal(recovered.source,'Open Food Facts search index');
let attempts=0;
await assert.rejects(searchBrowserCategory('en:hazelnut-spreads',{parseRecord,validBarcode,fetcher:async()=>{attempts++;return new Response('{}',{status:429,headers:{'content-type':'application/json','retry-after':'45'}});}}),e=>e.code==='rate_limited'&&e.retryAfter===45);
assert.equal(attempts,1);
const empty=await searchBrowserCategory('en:hazelnut-spreads',{parseRecord,validBarcode,fetcher:async(url)=>new Response(JSON.stringify(url.startsWith('https://search.')?{hits:[]}:{products:[]}),{status:200,headers:{'content-type':'application/json'}})});
assert.equal(empty.checked,0);
assert.deepEqual(empty.products,[]);
const html=await fs.readFile('index.html','utf8');
const map=html.match(/<script type="importmap">([^<]+)<\/script>/)?.[1];
assert(map,'Missing importmap');
const hash='sha256-'+crypto.createHash('sha256').update(map).digest('base64');
const headers=await fs.readFile('_headers','utf8');
assert(headers.includes(hash),'CSP must allow exact importmap bytes');
for(const dest of Object.values(JSON.parse(map).imports)){assert((await fs.stat('.'+dest)).isFile(),'Missing mapped module '+dest);}
const css=await fs.readFile('assets/release-11.13.0/app.css','utf8');
assert(css.includes('.fs14-profile-tile'),'Missing classification CSS');
assert(html.includes('"softwareVersion":"11.19.0"'));
console.log('FoodScan 11.13 query, fallback, CORS rules, CSP, import map and source classes: PASS');
