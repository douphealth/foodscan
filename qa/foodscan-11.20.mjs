import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {sourceIntegrity,enforceSourceIntegrity,validateLabelFacts} from '../assets/release-11.20.0/source-trust.js';
const sample={barcode:'80823131',name:'Product 80823131',brand:'',basis:null,provenance:'off',nutrition:{kcal:10,fat:10,saturatedFat:10,protein:null,carbohydrates:null,sugars:null},qualityWarnings:['nutrition-packaging-as-sold-100g-energy-value-in-kcal-does-not-match-value-in-kj','nutrition-packaging-as-sold-100g-values-are-all-identical'],fetchedAt:Date.now()};
assert.equal(sourceIntegrity(sample).status,'rejected','Contradictory scan must fail');
const masked=enforceSourceIntegrity(sample);
assert.equal(masked.nutrition.kcal,null);
assert.equal(masked.nutrition.fat,null);
assert.equal(masked.nutrition.saturatedFat,null);
assert.equal(masked.basis,null);
assert.equal(masked.partial,true);
assert.equal(sourceIntegrity(masked).status,'rejected','Quarantine must survive storage');
const valid={barcode:'3017620422003',name:'Nutella',brand:'Ferrero',basis:'g',provenance:'off',nutrition:{kcal:539,protein:6.3,carbohydrates:57.5,sugars:56.3,fat:30.9,saturatedFat:10.6,fiber:0,salt:.11},qualityWarnings:[]};
assert.equal(sourceIntegrity(valid).status,'usable');
assert.equal(enforceSourceIntegrity(valid).nutrition.kcal,539);
assert.equal(sourceIntegrity({...valid,provenance:'local'}).status,'local');
assert(validateLabelFacts({kcal:10,fat:10},'g').length,'Reject calorie impossible');
assert.equal(validateLabelFacts({kcal:539,fat:30.9,saturatedFat:10.6,protein:6.3,carbohydrates:57.5,sugars:56.3},'g').length,0);
const html=await fs.readFile('index.html','utf8');
const map=html.split('<script type="importmap">')[1]?.split('</script>')[0];
assert(map);
const hash='sha256-'+crypto.createHash('sha256').update(map).digest('base64');
assert((await fs.readFile('_headers','utf8')).includes(hash),'CSP hash mismatch');
for(const file of Object.values(JSON.parse(map).imports))await fs.stat('.'+file);
for(const name of ['app.css','app.js','source-trust.js','model.js','result.js','api-core.js','api.js','engine.js','views.js','report-audit.js'])await fs.stat('assets/release-11.20.0/'+name);
assert((await fs.readFile('sw.js','utf8')).includes('foodscan-shell-11.21.0'));
console.log('PASS source quarantine, valid control, manual entry and release integrity');
